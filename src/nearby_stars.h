    // 連星: 伴星の主星に対する軌道（周期 [年], 近点通過 [年], 離心率, 軌道長半径 [秒角], 傾斜角・昇交点・近点引数 [deg]）と、
    // 重心からの位置に掛ける係数（主星 −m伴/m全, 伴星 +m主/m全）。単独の星は P = 0
